import asyncio,json
from pathlib import Path
from playwright.async_api import async_playwright
OUT=Path('/tmp/browser/flashreserve')
async def main():
 async with async_playwright() as p:
  browser=await p.chromium.launch(headless=True)
  context=await browser.new_context(viewport={'width':1280,'height':1800})
  page=await context.new_page()
  errors=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  await page.goto('http://localhost:8080',wait_until='networkidle')
  await page.screenshot(path=str(OUT/'desktop.png'))
  await page.get_by_role('link',name='Explore flash sales',exact=True).click()
  await page.get_by_role('tab',name='Upcoming',exact=True).click()
  await page.get_by_role('textbox',name='Search campaigns').fill('iphone')
  await page.get_by_label('Sort campaigns').select_option('newest')
  await page.get_by_role('button',name='Try again',exact=True).click()
  await page.get_by_role('status').filter(has_text='No reservations have been placed').wait_for()
  await page.get_by_role('button',name='My reservation').click()
  await page.get_by_label('Reservation ID',exact=True).fill('res_browser_check')
  await page.get_by_role('button',name='Check reservation',exact=True).click()
  await page.wait_for_url('**/reservations/res_browser_check')
  await page.get_by_role('button',name='Check again',exact=True).click()
  await page.get_by_role('status').wait_for()
  await page.screenshot(path=str(OUT/'reservation.png'))
  await page.goto('http://localhost:8080/checkout/res_browser_check',wait_until='networkidle')
  assert await page.get_by_role('button',name='Complete mock payment').is_disabled()
  await page.goto('http://localhost:8080/admin',wait_until='networkidle')
  await page.get_by_role('link',name='System health',exact=True).click()
  await page.get_by_role('button',name='Check availability',exact=True).click()
  await page.get_by_role('status').wait_for()
  await page.screenshot(path=str(OUT/'admin.png'))
  await page.get_by_role('link',name='Settings',exact=True).click()
  await page.get_by_text('http://localhost:3000/api',exact=True).wait_for()
  await page.set_viewport_size({'width':390,'height':844})
  await page.goto('http://localhost:8080',wait_until='networkidle')
  await page.screenshot(path=str(OUT/'mobile.png'))
  assert await page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
  await page.goto('http://localhost:8080/admin',wait_until='networkidle')
  await page.get_by_role('button',name='Open navigation').click()
  await page.get_by_role('link',name='Reservations',exact=True).click()
  await page.get_by_role('heading',name='Reservations',exact=True).wait_for()
  assert await page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
  await page.screenshot(path=str(OUT/'admin-mobile.png'))
  print(json.dumps({'customer_flow':'passed with honest unavailable state','checkout':'disabled, no payment submitted','admin':'no private data, navigation passed','mobile':'no horizontal overflow','runtime_errors':errors}))
  await browser.close()
asyncio.run(main())
